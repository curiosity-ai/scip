#!/usr/bin/env bash
# Regenerates src/ScipSharp/Protos/scip.proto from the upstream schema kept in .reference/scip/scip.proto.
#
# Two changes, neither affecting the wire format:
#  1. `option csharp_namespace = "ScipSharp";` so the generated types live in namespace ScipSharp (not `Scip`).
#  2. message `Descriptor` is renamed `SymbolDescriptor`: C# forbids a class having a member of the same name as
#     itself, and every generated message has a static `Descriptor` property.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "// NOTE: generated by tools/sync-proto.sh from .reference/scip/scip.proto. Do not edit by hand."
  echo "// Changes: csharp_namespace = ScipSharp; message Descriptor is renamed SymbolDescriptor (C# naming conflict)."
  sed -E -e 's/^message Descriptor \{/message SymbolDescriptor {/' \
         -e 's/^package scip;$/package scip;\n\noption csharp_namespace = "ScipSharp";/' \
         -e 's/^(\s*repeated )Descriptor /\1SymbolDescriptor /' \
         "$root/.reference/scip/scip.proto"
} > "$root/src/ScipSharp/Protos/scip.proto"
