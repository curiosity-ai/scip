#!/usr/bin/env bash
# Regenerates src/Scip/Protos/scip.proto from the upstream schema kept in .reference/scip/scip.proto.
#
# The only change: message `Descriptor` is renamed `SymbolDescriptor`. C# forbids a class having a member of the
# same name as itself, and every generated message has a static `Descriptor` property. Wire format is unaffected.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "// NOTE: generated by tools/sync-proto.sh from .reference/scip/scip.proto. Do not edit by hand."
  echo "// Only change: message Descriptor is renamed SymbolDescriptor (C# naming conflict)."
  sed -E -e 's/^message Descriptor \{/message SymbolDescriptor {/' \
         -e 's/^(\s*repeated )Descriptor /\1SymbolDescriptor /' \
         "$root/.reference/scip/scip.proto"
} > "$root/src/Scip/Protos/scip.proto"
