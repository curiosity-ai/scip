using System.Collections.Frozen;

namespace ScipSharp.Indexer.Sql.Syntax;

/// <summary>Keyword classes used by the tolerant parser (all upper case).</summary>
internal static class Keywords
{
    private static FrozenSet<string> Set(string words) =>
        words.Split((char[])[' ', '\n', '\r'], StringSplitOptions.RemoveEmptyEntries).ToFrozenSet(StringComparer.Ordinal);

    /// <summary>Words that are never a column/table/alias name in expression or alias position.</summary>
    public static readonly FrozenSet<string> Reserved = Set("""
        SELECT FROM WHERE AND OR NOT NULL IS IN LIKE ILIKE RLIKE REGEXP SIMILAR BETWEEN CASE WHEN THEN ELSE END AS ON
        JOIN INNER LEFT RIGHT FULL OUTER CROSS NATURAL USING GROUP BY ORDER HAVING LIMIT OFFSET FETCH UNION ALL DISTINCT
        INTERSECT EXCEPT MINUS INTO VALUES INSERT UPDATE DELETE SET CREATE ALTER DROP TABLE WITH RECURSIVE TRUE FALSE
        UNKNOWN EXISTS ANY SOME ASC DESC NULLS PRIMARY FOREIGN REFERENCES CHECK CONSTRAINT UNIQUE DEFAULT COLLATE CAST
        OVER PARTITION WINDOW ROWS UNBOUNDED PRECEDING FOLLOWING FILTER WITHIN INTERVAL ESCAPE RETURNING
        LATERAL APPLY TOP PERCENT TIES OUTPUT DECLARE BEGIN IF WHILE RETURN EXEC EXECUTE PRINT RAISERROR THROW OPEN
        CLOSE DEALLOCATE GOTO BREAK CONTINUE TRUNCATE GRANT REVOKE CALL PERFORM RAISE EXIT ELSIF ELSEIF LOOP DO FOR
        QUALIFY PIVOT UNPIVOT CONNECT PRIOR MERGE MATCHED XOR DIV OVERLAPS ISNULL NOTNULL SEPARATOR LEADING
        TRAILING BOTH STRAIGHT_JOIN USE COMMIT ROLLBACK SAVEPOINT OPTION TABLESAMPLE DISTINCTROW UNTIL REPEAT
        CURRENT_DATE CURRENT_TIME CURRENT_TIMESTAMP LOCALTIME LOCALTIMESTAMP CURRENT_USER SESSION_USER SYSTEM_USER
        CURRENT_SCHEMA CURRENT_CATALOG CURRENT_ROLE SYSDATE SYSTIMESTAMP ROWNUM COLLATION BINARY AT TO OF GLOB MOD
        """);

    /// <summary>Reserved words that act as operands (literals and niladic functions).</summary>
    public static readonly FrozenSet<string> Operands = Set("""
        NULL TRUE FALSE UNKNOWN DEFAULT CURRENT_DATE CURRENT_TIME CURRENT_TIMESTAMP LOCALTIME LOCALTIMESTAMP CURRENT_USER
        SESSION_USER SYSTEM_USER CURRENT_SCHEMA CURRENT_CATALOG CURRENT_ROLE SYSDATE SYSTIMESTAMP ROWNUM
        """);

    /// <summary>Words that end an expression in clause position (outside parentheses and CASE).</summary>
    public static readonly FrozenSet<string> ClauseStops = Set("""
        FROM WHERE GROUP HAVING ORDER LIMIT OFFSET FETCH UNION INTERSECT EXCEPT MINUS WINDOW QUALIFY INTO ON USING
        JOIN INNER LEFT RIGHT FULL CROSS NATURAL OUTER APPLY STRAIGHT_JOIN RETURNING OUTPUT SET VALUES THEN LOOP DO AS
        WHEN ELSE END BEGIN DECLARE SELECT INSERT UPDATE DELETE MERGE WITH IF WHILE RETURN EXEC EXECUTE PRINT RAISERROR
        THROW OPEN CLOSE DEALLOCATE GOTO BREAK CONTINUE TRUNCATE CREATE ALTER DROP GRANT REVOKE CALL PERFORM RAISE EXIT
        ELSIF ELSEIF FOR USE COMMIT ROLLBACK SAVEPOINT CONNECT START PIVOT UNPIVOT OPTION TABLESAMPLE UNTIL REPEAT
        LANGUAGE RETURNS ASC DESC NULLS
        """);

    /// <summary>Keywords that may also be function names when followed by <c>(</c>.</summary>
    public static readonly FrozenSet<string> FunctionLike = Set("""
        LEFT RIGHT IF REPLACE INSERT VALUES CHAR FORMAT ISNULL COALESCE NULLIF CAST CONVERT EXISTS ANY SOME ALL
        GROUPING ROW ARRAY MOD DATE TIME TIMESTAMP INTERVAL TRIM SUBSTRING POSITION EXTRACT OVERLAY USER DEFAULT
        COLLATION TRUNCATE MERGE MATCH
        """);

    /// <summary>Statement-starting words: in T-SQL scripts (no semicolons) a statement ends when one of these begins.</summary>
    public static readonly FrozenSet<string> StatementStarts = Set("""
        SELECT INSERT UPDATE DELETE MERGE WITH DECLARE SET IF WHILE RETURN EXEC EXECUTE PRINT RAISERROR THROW OPEN CLOSE
        DEALLOCATE GOTO BREAK CONTINUE TRUNCATE CREATE ALTER DROP GRANT REVOKE CALL USE COMMIT ROLLBACK SAVEPOINT BEGIN
        END FETCH
        """);

    /// <summary>Column-constraint keywords that end a column's data type.</summary>
    public static readonly FrozenSet<string> ColumnConstraintStarts = Set("""
        CONSTRAINT NOT NULL DEFAULT PRIMARY UNIQUE REFERENCES CHECK COLLATE GENERATED IDENTITY AUTO_INCREMENT
        AUTOINCREMENT COMMENT ON AS ROWGUIDCOL SPARSE FILESTREAM MASKED ENCRYPTED HIDDEN INVISIBLE VISIBLE STORAGE
        COMPRESSION ENABLE DISABLE CHARSET KEY ENCODE DISTKEY SORTKEY OPTIONS WITH COLUMN_FORMAT
        """);

    /// <summary>Words that continue a multi-word data type (<c>double precision</c>, <c>timestamp with time zone</c>).</summary>
    public static readonly FrozenSet<string> TypeContinuations = Set("""
        PRECISION VARYING UNSIGNED SIGNED ZEROFILL ZONE LOCAL WITHOUT LARGE OBJECT VARCHAR
        """);

    /// <summary>Common built-in type names (to tell <c>name type</c> from <c>type</c> in unnamed PostgreSQL parameters).</summary>
    public static readonly FrozenSet<string> BuiltinTypes = Set("""
        INT INTEGER INT2 INT4 INT8 BIGINT SMALLINT TINYINT MEDIUMINT TEXT VARCHAR CHAR CHARACTER NCHAR NVARCHAR NUMERIC
        DECIMAL REAL DOUBLE FLOAT FLOAT4 FLOAT8 BOOLEAN BOOL BIT DATE TIME TIMESTAMP TIMESTAMPTZ TIMETZ INTERVAL JSON JSONB
        UUID BYTEA BLOB CLOB NCLOB MONEY SERIAL BIGSERIAL SMALLSERIAL XML INET CIDR MACADDR POINT LINE BOX POLYGON CIRCLE
        TSVECTOR TSQUERY OID REGCLASS ANYELEMENT ANYARRAY ANYNONARRAY ANYENUM ANYRANGE RECORD TRIGGER VOID INTERNAL CSTRING
        NUMBER VARCHAR2 NVARCHAR2 RAW LONG BINARY_INTEGER PLS_INTEGER BINARY_FLOAT BINARY_DOUBLE DATETIME DATETIME2
        SMALLDATETIME DATETIMEOFFSET UNIQUEIDENTIFIER VARBINARY IMAGE NTEXT SQL_VARIANT HIERARCHYID GEOGRAPHY GEOMETRY
        TINYTEXT MEDIUMTEXT LONGTEXT TINYBLOB MEDIUMBLOB LONGBLOB ENUM YEAR REFCURSOR NAME VARBIT
        """);

    public static bool IsReserved(string upper) => Reserved.Contains(upper);
}
